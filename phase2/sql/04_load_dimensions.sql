-- =============================================================================
-- THE BOOT ROOM - Football Data Warehouse
-- Script: 04_load_dimensions.sql
-- Purpose: Load all 6 dimensions in project_dw from project_staging tables.
--
-- Prerequisites (run in order):
--   00_create_schemas.sql
--   01_staging_ddl.sql
--   02_dw_ddl.sql
--   03_reporting_ddl.sql
--   Python ETL: 02_load_staging.py
--
-- Dimension load order (dependency-driven):
--   1. dim_date        – date spine, no staging dependency
--   2. dim_season      – depends on stg_season, stg_competition
--   3. dim_team        – depends on stg_team
--   4. dim_player      – depends on stg_player
--   5. dim_venue       – depends on stg_match (stadium data)
--   6. dim_match       – depends on dim_season, dim_team, dim_venue, stg_match
--
-- Surrogate-key mapping pattern:
--   Natural keys from staging (text) are CAST to INTEGER and matched against
--   the integer surrogate PKs in the DW dimensions. The SERIAL surrogate keys
--   (e.g. season_key, team_key, venue_key) are generated by the DW table on
--   INSERT; dim_match JOINs back to those DW tables to resolve the surrogate
--   keys before inserting into dim_match.
-- =============================================================================

DO $$
DECLARE
    v_count INTEGER;
BEGIN

    -- =========================================================================
    -- 1. dim_date
    -- Builds a complete date spine from 2010-01-01 to 2030-12-31 using
    -- generate_series. No staging dependency; purely computed.
    -- ON CONFLICT DO NOTHING makes this re-runnable safely.
    -- =========================================================================
    RAISE NOTICE 'Loading dim_date...';

    INSERT INTO project_dw.dim_date (
        date_key,
        full_date,
        year,
        quarter,
        month,
        month_name,
        day_of_month,
        day_of_week,
        day_name,
        is_weekend,
        week_of_year,
        is_leap_year
    )
    SELECT
        CAST(TO_CHAR(d, 'YYYYMMDD') AS INTEGER)                        AS date_key,
        d::DATE                                                         AS full_date,
        EXTRACT(YEAR    FROM d)::SMALLINT                               AS year,
        EXTRACT(QUARTER FROM d)::SMALLINT                               AS quarter,
        EXTRACT(MONTH   FROM d)::SMALLINT                               AS month,
        TRIM(TO_CHAR(d, 'Month'))                                       AS month_name,
        EXTRACT(DAY     FROM d)::SMALLINT                               AS day_of_month,
        EXTRACT(ISODOW  FROM d)::SMALLINT                               AS day_of_week,
        TRIM(TO_CHAR(d, 'Day'))                                         AS day_name,
        (EXTRACT(ISODOW FROM d) >= 6)                                   AS is_weekend,
        EXTRACT(WEEK    FROM d)::SMALLINT                               AS week_of_year,
        (
            EXTRACT(YEAR FROM d) % 4 = 0
            AND (
                EXTRACT(YEAR FROM d) % 100 != 0
                OR EXTRACT(YEAR FROM d) % 400 = 0
            )
        )                                                               AS is_leap_year
    FROM generate_series(
        '2010-01-01'::DATE,
        '2030-12-31'::DATE,
        '1 day'::INTERVAL
    ) AS gs(d)
    ON CONFLICT (date_key) DO NOTHING;

    GET DIAGNOSTICS v_count = ROW_COUNT;
    RAISE NOTICE 'dim_date: % rows inserted/updated', v_count;


    -- =========================================================================
    -- 2. dim_season
    -- Loads seasons from stg_season, enriching with competition metadata from
    -- stg_competition via a LEFT JOIN on competition_id.
    -- COALESCE/NULLIF normalise missing competition_gender to 'male'.
    -- ON CONFLICT updates season_name and _updated_at so reruns stay current.
    -- =========================================================================
    RAISE NOTICE 'Loading dim_season...';

    INSERT INTO project_dw.dim_season (
        season_id,
        season_name,
        competition_id,
        competition_name,
        country_name,
        competition_gender,
        is_youth,
        is_international
    )
    SELECT DISTINCT
        CAST(s.season_id AS INTEGER),
        TRIM(s.season_name),
        CAST(s.competition_id AS INTEGER),
        INITCAP(TRIM(s.competition_name)),
        INITCAP(TRIM(s.country_name)),
        COALESCE(NULLIF(TRIM(c.competition_gender), ''), 'male'),
        (LOWER(TRIM(c.competition_youth))         = 'true'),
        (LOWER(TRIM(c.competition_international)) = 'true')
    FROM project_staging.stg_season s
    LEFT JOIN project_staging.stg_competition c
           ON s.competition_id = c.competition_id
    WHERE s.season_id IS NOT NULL
      AND s.season_id != ''
    ON CONFLICT (season_id) DO UPDATE SET
        season_name  = EXCLUDED.season_name,
        _updated_at  = CURRENT_TIMESTAMP;

    GET DIAGNOSTICS v_count = ROW_COUNT;
    RAISE NOTICE 'dim_season: % rows inserted/updated', v_count;


    -- =========================================================================
    -- 3. dim_team
    -- Loads unique teams from stg_team. NULLIF guards against empty strings
    -- for optional columns (team_short_name, country_name).
    -- ON CONFLICT updates team_name and _updated_at.
    -- =========================================================================
    RAISE NOTICE 'Loading dim_team...';

    INSERT INTO project_dw.dim_team (
        team_id,
        team_name,
        team_short_name,
        country_name
    )
    SELECT DISTINCT
        CAST(team_id AS INTEGER),
        INITCAP(TRIM(team_name)),
        INITCAP(TRIM(NULLIF(team_short_name, ''))),
        INITCAP(TRIM(NULLIF(country_name,   '')))
    FROM project_staging.stg_team
    WHERE team_id   IS NOT NULL AND team_id   != ''
      AND team_name IS NOT NULL AND team_name != ''
    ON CONFLICT (team_id) DO UPDATE SET
        team_name   = EXCLUDED.team_name,
        _updated_at = CURRENT_TIMESTAMP;

    GET DIAGNOSTICS v_count = ROW_COUNT;
    RAISE NOTICE 'dim_team: % rows inserted/updated', v_count;


    -- =========================================================================
    -- 4. dim_player
    -- DISTINCT ON (player_id) keeps exactly one row per player; ties broken by
    -- player_name alphabetically. NULLIF handles empty nationality / position.
    -- ON CONFLICT updates player_name and _updated_at.
    -- =========================================================================
    RAISE NOTICE 'Loading dim_player...';

    INSERT INTO project_dw.dim_player (
        player_id,
        player_name,
        nationality,
        primary_position
    )
    SELECT DISTINCT ON (CAST(player_id AS INTEGER))
        CAST(player_id AS INTEGER),
        INITCAP(TRIM(player_name)),
        INITCAP(TRIM(NULLIF(nationality, ''))),
        INITCAP(TRIM(NULLIF(position,    '')))
    FROM project_staging.stg_player
    WHERE player_id   IS NOT NULL AND player_id   != ''
      AND player_name IS NOT NULL AND player_name != ''
    ORDER BY CAST(player_id AS INTEGER), player_name
    ON CONFLICT (player_id) DO UPDATE SET
        player_name = EXCLUDED.player_name,
        _updated_at = CURRENT_TIMESTAMP;

    GET DIAGNOSTICS v_count = ROW_COUNT;
    RAISE NOTICE 'dim_player: % rows inserted/updated', v_count;


    -- =========================================================================
    -- 5. dim_venue
    -- Derives unique venues from stg_match using stadium_name as the natural
    -- key. NULLIF handles rows with no city or country.
    -- ON CONFLICT (stadium_name) DO NOTHING – venues are static once created.
    -- =========================================================================
    RAISE NOTICE 'Loading dim_venue...';

    INSERT INTO project_dw.dim_venue (
        stadium_name,
        city,
        country_name
    )
    SELECT DISTINCT
        INITCAP(TRIM(stadium_name)),
        INITCAP(TRIM(NULLIF(city,         ''))),
        INITCAP(TRIM(NULLIF(country_name, '')))
    FROM project_staging.stg_match
    WHERE stadium_name IS NOT NULL
      AND TRIM(stadium_name) != ''
    ON CONFLICT (stadium_name) DO NOTHING;

    GET DIAGNOSTICS v_count = ROW_COUNT;
    RAISE NOTICE 'dim_venue: % rows inserted/updated', v_count;


    -- =========================================================================
    -- 6. dim_match
    -- Most complex load: resolves four surrogate keys by joining back to the
    -- DW dimensions already populated above.
    --
    --   season_key     <- dim_season.season_key  (matched on season_id)
    --   home_team_key  <- dim_team.team_key      (matched on home_team_id)
    --   away_team_key  <- dim_team.team_key      (matched on away_team_id)
    --   venue_key      <- dim_venue.venue_key    (matched on stadium_name)
    --   date_key       <- computed YYYYMMDD INT  (links to dim_date)
    --
    -- DISTINCT ON (match_id) + ORDER BY match_id removes staging duplicates.
    -- ON CONFLICT updates scores (the only mutable match attributes).
    -- =========================================================================
    RAISE NOTICE 'Loading dim_match...';

    INSERT INTO project_dw.dim_match (
        match_id,
        match_date,
        kick_off,
        match_week,
        competition_stage,
        home_score,
        away_score,
        referee,
        season_key,
        home_team_key,
        away_team_key,
        venue_key,
        date_key
    )
    SELECT DISTINCT ON (CAST(sm.match_id AS INTEGER))
        CAST(sm.match_id AS INTEGER),
        sm.match_date::DATE,
        NULLIF(TRIM(sm.kick_off),    '')::TIME,
        NULLIF(sm.match_week,        '')::SMALLINT,
        INITCAP(TRIM(COALESCE(NULLIF(sm.competition_stage, ''), 'Regular Season'))),
        NULLIF(sm.home_score,        '')::SMALLINT,
        NULLIF(sm.away_score,        '')::SMALLINT,
        INITCAP(TRIM(NULLIF(sm.referee_name, ''))),
        ds.season_key,
        dht.team_key,
        dat.team_key,
        dv.venue_key,
        CAST(TO_CHAR(sm.match_date::DATE, 'YYYYMMDD') AS INTEGER)
    FROM project_staging.stg_match sm
    -- Resolve season surrogate key
    JOIN project_dw.dim_season ds
      ON ds.season_id = CAST(sm.season_id AS INTEGER)
    -- Resolve home-team surrogate key
    JOIN project_dw.dim_team dht
      ON dht.team_id  = CAST(sm.home_team_id AS INTEGER)
    -- Resolve away-team surrogate key
    JOIN project_dw.dim_team dat
      ON dat.team_id  = CAST(sm.away_team_id AS INTEGER)
    -- Venue is optional (LEFT JOIN): some matches may have no stadium recorded
    LEFT JOIN project_dw.dim_venue dv
      ON dv.stadium_name = INITCAP(TRIM(sm.stadium_name))
    WHERE sm.match_id   IS NOT NULL AND sm.match_id   != ''
      AND sm.match_date IS NOT NULL AND sm.match_date != ''
    ORDER BY CAST(sm.match_id AS INTEGER)
    ON CONFLICT (match_id) DO UPDATE SET
        home_score  = EXCLUDED.home_score,
        away_score  = EXCLUDED.away_score;

    GET DIAGNOSTICS v_count = ROW_COUNT;
    RAISE NOTICE 'dim_match: % rows inserted/updated', v_count;


    RAISE NOTICE '=== 04_load_dimensions.sql complete ===';

END $$;
